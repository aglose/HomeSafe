#!/usr/bin/env python3
"""
Decides whether a Dependabot pull request is nothing but version numbers.

The "Dependency updates" workflow merges a Dependabot pull request by itself once CI is green,
but only when this script says the whole difference from main is a plain version bump. Anything
else (a source file, a new dependency, a line added or removed) is a change someone has to read,
and the pull request waits for them.

    python3 scripts/ci/dependency_gate.py --base <commit> --head <commit> [--json out.json] [--markdown out.md]

Exit status 0 means "only version numbers", 1 means "needs a person", 2 means it could not tell.
It reads both commits out of git and never checks out or runs anything from the pull request,
so it is safe to run from main against a branch nobody has looked at.

Two things have to hold:

1. Every changed file is a dependency manifest this script knows, and every changed line in it
   is a version (or, for the Gradle wrapper, the files Gradle regenerates with one).
2. If anyone other than Dependabot has committed to the branch (the repair job in the workflow
   does, to hold back an update that broke the build), each line is either what main has or what
   Dependabot proposed. So a later commit can take updates out, but cannot change one or add one.

Runs with nothing but the standard library (Python 3.11 or newer, for tomllib).
"""

from __future__ import annotations

import argparse
import fnmatch
import json
import re
import subprocess
import sys
import tomllib
from dataclasses import dataclass, field

DEPENDABOT_AUTHOR = "dependabot[bot]"

WRAPPER_PROPERTIES = "gradle/wrapper/gradle-wrapper.properties"
# Regenerated by the wrapper task along with the properties file. They are not version numbers, so
# they are accepted only byte for byte as Dependabot committed them, and only beside a new version.
WRAPPER_COMPANIONS = ("gradle/wrapper/gradle-wrapper.jar", "gradlew", "gradlew.bat")

VERSION = r"[A-Za-z0-9_.+!\-]+"

CATALOG_LINE = re.compile(r'^(?P<pre>\s*[A-Za-z0-9_.\-]+\s*=\s*)"(?P<version>[^"\\]*)"(?P<post>\s*(?:#.*)?)$')
TABLE_HEADER = re.compile(r"^\s*\[\s*(?P<name>[^\[\]]+?)\s*\]\s*(?:#.*)?$")
PROPERTY_LINE = re.compile(r"^(?P<key>[A-Za-z0-9_.]+)=(?P<value>.*)$")
GRADLE_DISTRIBUTION = re.compile(
    r"^https\\://services\.gradle\.org/distributions/gradle-[0-9][0-9A-Za-z.\-]*-(?:bin|all)\.zip$"
)
# A trailing comment (Dependabot keeps `# v4.1.1` beside a pinned commit) may change with the version.
USES_LINE = re.compile(
    r"""^(?P<pre>\s*(?:-\s+)?uses:\s*["']?[^@\s"'#]+@)(?P<version>[^\s"'#]+)(?P<post>["']?)\s*(?:\#.*)?$"""
)
REQUIREMENT_LINE = re.compile(
    rf"^(?P<pre>[A-Za-z0-9_.\-]+(?:\[[^\]]+\])?\s*==\s*)(?P<version>{VERSION})(?P<post>\s*(?:[;#].*)?)$"
)
FROM_LINE = re.compile(
    r"^(?P<pre>\s*FROM\s+(?:--platform=\S+\s+)?[^\s:@]+)"
    r"(?P<version>(?::[^\s@]+)?(?:@sha256:[0-9a-f]{64})?)"
    r"(?P<post>(?:\s+[Aa][Ss]\s+\S+)?\s*)$"
)
PLUGIN_LINE = re.compile(
    rf"""^(?P<pre>\s*id\s*\(?\s*["'][^"']+["']\s*\)?\s+version\s+["'])(?P<version>{VERSION})(?P<post>["'].*)$"""
)
COORDINATES_LINE = re.compile(
    rf"""^(?P<pre>.*["'][A-Za-z0-9_.\-]+:[A-Za-z0-9_.\-]+:)(?P<version>{VERSION})(?P<post>["'].*)$"""
)


class GateError(Exception):
    """The gate could not reach a verdict (a bad commit, a git failure)."""


@dataclass
class FileVerdict:
    path: str
    problems: list[str] = field(default_factory=list)
    updates: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.problems


@dataclass
class Verdict:
    simple: bool
    base: str
    head: str
    dependabot_commit: str | None
    other_commits: int
    problems: list[str]
    files: list[FileVerdict]
    held_back: list[str]

    def as_json(self) -> dict:
        return {
            "simple": self.simple,
            "base": self.base,
            "head": self.head,
            "dependabot_commit": self.dependabot_commit,
            "other_commits": self.other_commits,
            "problems": self.problems,
            "files": [{"path": f.path, "ok": f.ok, "problems": f.problems, "updates": f.updates} for f in self.files],
            "held_back": self.held_back,
        }

    def as_markdown(self) -> str:
        lines: list[str] = []
        if self.simple:
            lines.append("Every changed line is a version number in a dependency manifest.")
        else:
            lines.append("This is more than version numbers, so it is not merged automatically:")
            lines.append("")
            lines += [f"- {problem}" for problem in self.problems]
            for changed in self.files:
                lines += [f"- `{changed.path}`: {problem}" for problem in changed.problems]
        # One line per update, however many times a workflow uses the same action.
        updates = list(dict.fromkeys((changed.path, update) for changed in self.files for update in changed.updates))
        if updates:
            lines += ["", "Updates:", ""]
            lines += [f"- `{path}`: {update}" for path, update in updates]
        if self.held_back:
            lines += ["", "Held back (still at main's version):", ""]
            lines += [f"- {entry}" for entry in self.held_back]
        return "\n".join(lines) + "\n"


class Repo:
    def __init__(self, path: str = "."):
        self.path = path

    def git(self, *args: str) -> bytes:
        result = subprocess.run(["git", "-C", self.path, *args], capture_output=True)
        if result.returncode != 0:
            raise GateError(f"git {' '.join(args)}: {result.stderr.decode(errors='replace').strip()}")
        return result.stdout

    def resolve(self, rev: str) -> str:
        return self.git("rev-parse", "--verify", f"{rev}^{{commit}}").decode().strip()

    def blob(self, rev: str, path: str) -> bytes | None:
        result = subprocess.run(["git", "-C", self.path, "cat-file", "blob", f"{rev}:{path}"], capture_output=True)
        return result.stdout if result.returncode == 0 else None

    def changes(self, base: str, head: str) -> list[tuple[str, str]]:
        """(status, path) for every file that differs. Renames show as a delete and an add."""
        fields = self.git("diff", "--name-status", "--no-renames", "-z", base, head).decode().split("\0")
        return [(fields[i], fields[i + 1]) for i in range(0, len(fields) - 1, 2)]

    def commits(self, base: str, head: str) -> list[tuple[str, str]]:
        """(sha, author name) for each commit after base, oldest first."""
        out = self.git("rev-list", "--reverse", "--format=%H%x00%an", "--no-commit-header", f"{base}..{head}").decode()
        return [tuple(line.split("\0", 1)) for line in out.splitlines() if line]


def text_lines(data: bytes) -> list[str] | None:
    try:
        return data.decode("utf-8").splitlines()
    except UnicodeDecodeError:
        return None


def changed_pairs(old: list[str], new: list[str]) -> list[tuple[int, str, str]] | None:
    """The lines that differ, as (number, old, new), or None when lines were added or removed."""
    if len(old) != len(new):
        return None
    return [(i + 1, a, b) for i, (a, b) in enumerate(zip(old, new)) if a != b]


def same_but_version(pattern: re.Pattern, old: str, new: str) -> tuple[str, str] | None:
    """Both lines match and only the version group differs: (old version, new version)."""
    a, b = pattern.match(old), pattern.match(new)
    if not a or not b or a["pre"] != b["pre"] or a["post"] != b["post"]:
        return None
    return a["version"], b["version"]


def check_line_by_line(verdict: FileVerdict, old: list[str], new: list[str], patterns, what: str) -> None:
    pairs = changed_pairs(old, new)
    if pairs is None:
        verdict.problems.append(f"lines were added or removed ({len(old)} → {len(new)})")
        return
    for number, a, b in pairs:
        for pattern in patterns:
            versions = same_but_version(pattern, a, b)
            if versions:
                # A base image's "version" is its `:tag`.
                before, after = (version.lstrip(":") for version in versions)
                verdict.updates.append(f"{describe(pattern, a)} {before} → {after}")
                break
        else:
            verdict.problems.append(f"line {number} changes something other than {what}: `{b.strip()}`")


def describe(pattern: re.Pattern, line: str) -> str:
    """The name of the thing a version line belongs to, for the report."""
    match = pattern.match(line)
    pre = match["pre"].strip()
    if pattern is USES_LINE:
        return pre.split("uses:", 1)[1].strip().strip("\"'").rstrip("@")
    if pattern is FROM_LINE:
        return pre.split()[-1]
    if pattern is PLUGIN_LINE:
        return re.search(r"""["']([^"']+)["']""", pre)[1]
    if pattern is COORDINATES_LINE:
        return re.search(r"""["']([^"']+):$""", pre)[1]
    return re.split(r"\s*=", pre)[0].strip()


def check_catalog(verdict: FileVerdict, old_bytes: bytes, new_bytes: bytes) -> None:
    old, new = text_lines(old_bytes), text_lines(new_bytes)
    pairs = changed_pairs(old, new)
    if pairs is None:
        verdict.problems.append(f"lines were added or removed ({len(old)} → {len(new)})")
        return
    table = table_per_line(old)
    for number, a, b in pairs:
        versions = same_but_version(CATALOG_LINE, a, b)
        if not versions or table[number - 1] != "versions":
            verdict.problems.append(f"line {number} changes something other than a `[versions]` entry: `{b.strip()}`")
        else:
            verdict.updates.append(f"{describe(CATALOG_LINE, a)} {versions[0]} → {versions[1]}")
    # The same question asked of the parsed file, so nothing rides in on a line that only looks
    # like a version entry (inside a multi-line string, say).
    try:
        before, after = tomllib.loads(old_bytes.decode()), tomllib.loads(new_bytes.decode())
    except (tomllib.TOMLDecodeError, UnicodeDecodeError) as error:
        verdict.problems.append(f"not valid TOML: {error}")
        return
    before_versions, after_versions = before.pop("versions", {}), after.pop("versions", {})
    if before != after:
        verdict.problems.append("something outside `[versions]` changed")
    if before_versions.keys() != after_versions.keys():
        verdict.problems.append("a `[versions]` entry was added or removed")
    if not all(isinstance(value, str) for value in after_versions.values()):
        verdict.problems.append("a `[versions]` entry is no longer a plain version string")


def table_per_line(lines: list[str]) -> list[str | None]:
    tables, current = [], None
    for line in lines:
        header = TABLE_HEADER.match(line)
        if header:
            current = header["name"]
        tables.append(current)
    return tables


def check_wrapper_properties(verdict: FileVerdict, old_bytes: bytes, new_bytes: bytes) -> None:
    old, new = text_lines(old_bytes), text_lines(new_bytes)
    pairs = changed_pairs(old, new)
    if pairs is None:
        verdict.problems.append(f"lines were added or removed ({len(old)} → {len(new)})")
        return
    for number, a, b in pairs:
        before, after = PROPERTY_LINE.match(a), PROPERTY_LINE.match(b)
        if not before or not after or before["key"] != after["key"]:
            verdict.problems.append(f"line {number} changes something other than a value: `{b.strip()}`")
        elif after["key"] == "distributionUrl":
            if GRADLE_DISTRIBUTION.match(after["value"]):
                verdict.updates.append(f"Gradle {gradle_version(before['value'])} → {gradle_version(after['value'])}")
            else:
                verdict.problems.append(f"line {number} is not a distribution from services.gradle.org: `{b.strip()}`")
        elif after["key"] == "distributionSha256Sum":
            if not re.fullmatch(r"[0-9a-f]{64}", after["value"]):
                verdict.problems.append(f"line {number} is not a SHA-256 checksum")
        else:
            verdict.problems.append(f"line {number} changes `{after['key']}`, not the Gradle version")


def gradle_version(url: str) -> str:
    match = re.search(r"gradle-(.+)-(?:bin|all)\.zip$", url)
    return match[1] if match else url


def is_workflow(path: str) -> bool:
    return fnmatch.fnmatch(path, ".github/workflows/*.y*ml") or (
        path.startswith(".github/actions/") and path.rsplit("/", 1)[-1] in ("action.yml", "action.yaml")
    )


def is_requirements(path: str) -> bool:
    return fnmatch.fnmatch(path.rsplit("/", 1)[-1], "requirements*.txt")


def is_dockerfile(path: str) -> bool:
    name = path.rsplit("/", 1)[-1]
    return name == "Dockerfile" or name.startswith("Dockerfile.") or name.endswith(".Dockerfile")


def is_gradle_script(path: str) -> bool:
    return path.endswith((".gradle.kts", ".gradle"))


def check_file(verdict: FileVerdict, old_bytes: bytes, new_bytes: bytes, changed: set[str]) -> None:
    path = verdict.path
    if path in WRAPPER_COMPANIONS:
        if WRAPPER_PROPERTIES not in changed:
            verdict.problems.append("the Gradle wrapper's files changed without a new Gradle version")
        return
    if text_lines(old_bytes) is None or text_lines(new_bytes) is None:
        verdict.problems.append("not a text file")
        return
    old, new = text_lines(old_bytes), text_lines(new_bytes)
    if path.endswith(".versions.toml"):
        check_catalog(verdict, old_bytes, new_bytes)
    elif path == WRAPPER_PROPERTIES:
        check_wrapper_properties(verdict, old_bytes, new_bytes)
    elif is_workflow(path):
        check_line_by_line(verdict, old, new, [USES_LINE], "the version of an action")
    elif is_requirements(path):
        check_line_by_line(verdict, old, new, [REQUIREMENT_LINE], "a pinned version")
    elif is_dockerfile(path):
        check_line_by_line(verdict, old, new, [FROM_LINE], "the tag of a base image")
    elif is_gradle_script(path):
        check_line_by_line(verdict, old, new, [PLUGIN_LINE, COORDINATES_LINE], "the version of a plugin or library")
    else:
        verdict.problems.append("not a dependency manifest")


def check_against_proposal(
    verdict: FileVerdict, base: bytes | None, proposed: bytes | None, head: bytes, held_back: list[str]
) -> None:
    """With commits after Dependabot's: each line is main's or Dependabot's, nothing new."""
    path = verdict.path
    if proposed is None or base is None:
        verdict.problems.append("changed by a later commit, not by Dependabot")
        return
    if path in WRAPPER_COMPANIONS or text_lines(head) is None:
        if head != proposed:
            verdict.problems.append("differs from what Dependabot committed")
        return
    base_lines, proposed_lines, head_lines = text_lines(base), text_lines(proposed), text_lines(head)
    if base_lines is None or proposed_lines is None or not len(base_lines) == len(proposed_lines) == len(head_lines):
        verdict.problems.append("a later commit added or removed lines")
        return
    for number, (was, wanted, now) in enumerate(zip(base_lines, proposed_lines, head_lines), start=1):
        if now == wanted:
            continue
        if now == was:
            held_back.append(f"`{path}` line {number}: `{was.strip()}` (Dependabot proposed `{wanted.strip()}`)")
        else:
            verdict.problems.append(f"line {number} is neither main's nor Dependabot's: `{now.strip()}`")


def evaluate(repo: Repo, base_rev: str, head_rev: str) -> Verdict:
    base, head = repo.resolve(base_rev), repo.resolve(head_rev)
    problems: list[str] = []
    held_back: list[str] = []

    # The branch is Dependabot's commits first, then possibly the repair job's on top.
    commits = repo.commits(base, head)
    dependabot_commit = None
    others = 0
    for sha, author in commits:
        if author == DEPENDABOT_AUTHOR:
            if others:
                problems.append("Dependabot's commits are not all first on the branch")
                break
            dependabot_commit = sha
        else:
            others += 1
    if dependabot_commit is None:
        problems.append("no commit by Dependabot on the branch")

    changes = repo.changes(base, head)
    changed = {path for _, path in changes}
    if not changes:
        problems.append("nothing differs from main")
    files: list[FileVerdict] = []
    for status, path in changes:
        verdict = FileVerdict(path)
        files.append(verdict)
        if status != "M":
            verdict.problems.append({"A": "a new file", "D": "a deleted file"}.get(status, f"status {status}"))
            continue
        old_bytes, new_bytes = repo.blob(base, path), repo.blob(head, path)
        check_file(verdict, old_bytes, new_bytes, changed)
        if others and dependabot_commit:
            check_against_proposal(verdict, old_bytes, repo.blob(dependabot_commit, path), new_bytes, held_back)

    if others and dependabot_commit:
        # Files a later commit put back to exactly what main has are not in the diff above.
        for _, path in repo.changes(base, dependabot_commit):
            if path not in changed:
                held_back.append(f"`{path}`: every change")

    simple = not problems and all(verdict.ok for verdict in files)
    return Verdict(simple, base, head, dependabot_commit, others, problems, files, held_back)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("--base", required=True, help="the commit on main the branch started from")
    parser.add_argument("--head", required=True, help="the pull request's head commit")
    parser.add_argument("--repo", default=".", help="path to the git repository")
    parser.add_argument("--json", help="write the verdict here as JSON")
    parser.add_argument("--markdown", help="write the verdict here as markdown, for a comment")
    args = parser.parse_args(argv)

    try:
        verdict = evaluate(Repo(args.repo), args.base, args.head)
    except GateError as error:
        print(f"dependency_gate: {error}", file=sys.stderr)
        return 2

    if args.json:
        with open(args.json, "w", encoding="utf-8") as out:
            json.dump(verdict.as_json(), out, indent=2)
    if args.markdown:
        with open(args.markdown, "w", encoding="utf-8") as out:
            out.write(verdict.as_markdown())
    print(verdict.as_markdown(), end="")
    return 0 if verdict.simple else 1


if __name__ == "__main__":
    sys.exit(main())
