#!/usr/bin/env node
// Writes every app icon in icons.mjs out for each place it is shown:
//
//   androidApp/src/main/res/drawable/ic_launcher[_<id>]_{background,foreground,monochrome}.xml
//   androidApp/src/main/res/mipmap-anydpi/ic_launcher[_<id>].xml      adaptive icons, themed too
//   androidApp/src/debug/res/drawable/ic_launcher_background.xml       debug's amber default
//   iosApp/iosApp/Assets.xcassets/AppIcon[-<Id>].appiconset/           1024 px PNGs
//   shared/src/commonMain/composeResources/drawable/app_icon_<id>.xml  the picker's previews
//   design/app-icons/                                                  SVGs and a contact sheet
//
// Run from the repository root:  node tools/app-icons/generate.mjs
// No npm packages: the PNGs come from the headless Chromium Playwright keeps in its cache (or
// CHROME=/path/to/chrome), and the SVG ↔ VectorDrawable translation is done here.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { ICONS } from './icons.mjs';

const ROOT = resolve(new URL('../..', import.meta.url).pathname);
const RES = join(ROOT, 'androidApp/src/main/res');
const DEBUG_RES = join(ROOT, 'androidApp/src/debug/res');
const ASSETS = join(ROOT, 'iosApp/iosApp/Assets.xcassets');
const COMPOSE = join(ROOT, 'shared/src/commonMain/composeResources/drawable');
const DESIGN = join(ROOT, 'design/app-icons');
const HEADER = 'Generated by tools/app-icons/generate.mjs from tools/app-icons/icons.mjs; edit those, not this.';

const isDefault = (icon) => icon === ICONS[0];
const androidName = (icon) => (isDefault(icon) ? 'ic_launcher' : `ic_launcher_${icon.id}`);
const iosName = (icon) => (isDefault(icon) ? 'AppIcon' : `AppIcon-${capitalise(icon.id)}`);
const capitalise = (s) => s[0].toUpperCase() + s.slice(1);

// ---- colours -------------------------------------------------------------------------------

function parseColour(c) {
  const [hex, alpha = '1'] = c.split('@');
  return { hex: hex.toUpperCase(), alpha: Number(alpha) };
}
const androidColour = (c) => {
  const { hex, alpha } = parseColour(c);
  const a = Math.round(alpha * 255).toString(16).toUpperCase().padStart(2, '0');
  return a === 'FF' ? hex : `#${a}${hex.slice(1)}`;
};

// ---- SVG -----------------------------------------------------------------------------------

function svgElements(elements, prefix) {
  const defs = [];
  const body = elements.map((e, i) => {
    const attrs = [`d="${e.d}"`];
    const paint = (p, kind) => {
      if (typeof p === 'string') {
        const { hex, alpha } = parseColour(p);
        attrs.push(`${kind}="${hex}"`);
        if (alpha !== 1) attrs.push(`${kind}-opacity="${alpha}"`);
        return;
      }
      const id = `${prefix}${i}${kind}`;
      const stops = p.stops
        .map(([o, c]) => {
          const { hex, alpha } = parseColour(c);
          return `<stop offset="${o}" stop-color="${hex}" stop-opacity="${alpha}"/>`;
        })
        .join('');
      if (p.linear) {
        const [x1, y1, x2, y2] = p.linear;
        defs.push(`<linearGradient id="${id}" gradientUnits="userSpaceOnUse" x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}">${stops}</linearGradient>`);
      } else {
        const [cx, cy, r] = p.radial;
        defs.push(`<radialGradient id="${id}" gradientUnits="userSpaceOnUse" cx="${cx}" cy="${cy}" r="${r}">${stops}</radialGradient>`);
      }
      attrs.push(`${kind}="url(#${id})"`);
    };
    if (e.fill) paint(e.fill, 'fill');
    else attrs.push('fill="none"');
    if (e.stroke) {
      paint(e.stroke, 'stroke');
      attrs.push(`stroke-width="${e.width}" stroke-linejoin="round" stroke-linecap="round"`);
    }
    if (e.evenOdd) attrs.push('fill-rule="evenodd"');
    return `<path ${attrs.join(' ')}/>`;
  });
  return { defs: defs.join(''), body: body.join('') };
}

// The icon as the platform shows it: the 72-wide window onto the 108 grid. Gradient ids are
// numbered across calls because the contact sheet puts every icon in one document.
let svgCount = 0;
function svg(layers, size = 1024) {
  const n = svgCount++;
  const parts = layers.map((elements, i) => svgElements(elements, `s${n}l${i}_`));
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="18 18 72 72">` +
    `<defs>${parts.map((p) => p.defs).join('')}</defs>${parts.map((p) => p.body).join('')}</svg>`;
}

// ---- VectorDrawable ------------------------------------------------------------------------

function vectorPaths(elements, indent) {
  const pad = ' '.repeat(indent);
  return elements.map((e) => {
    const attrs = [];
    const children = [];
    const paint = (p, kind) => {
      const attr = kind === 'fill' ? 'android:fillColor' : 'android:strokeColor';
      if (typeof p === 'string') {
        attrs.push(`${attr}="${androidColour(p)}"`);
        return;
      }
      const geometry = p.linear
        ? `android:type="linear" android:startX="${p.linear[0]}" android:startY="${p.linear[1]}" android:endX="${p.linear[2]}" android:endY="${p.linear[3]}"`
        : `android:type="radial" android:centerX="${p.radial[0]}" android:centerY="${p.radial[1]}" android:gradientRadius="${p.radial[2]}"`;
      const items = p.stops
        .map(([o, c]) => `${pad}            <item android:offset="${o}" android:color="${androidColour(c)}" />`)
        .join('\n');
      children.push(
        `${pad}    <aapt:attr name="${attr}">\n${pad}        <gradient ${geometry}>\n${items}\n${pad}        </gradient>\n${pad}    </aapt:attr>`,
      );
    };
    if (e.fill) paint(e.fill, 'fill');
    if (e.stroke) {
      paint(e.stroke, 'stroke');
      attrs.push(`android:strokeWidth="${e.width}"`, 'android:strokeLineJoin="round"', 'android:strokeLineCap="round"');
    }
    if (e.evenOdd) attrs.push('android:fillType="evenOdd"');
    attrs.push(`android:pathData="${e.d}"`);
    const open = `${pad}<path\n${attrs.map((a) => `${pad}    ${a}`).join('\n')}`;
    return children.length ? `${open}>\n${children.join('\n')}\n${pad}</path>` : `${open} />`;
  }).join('\n');
}

const usesGradient = (elements) => elements.some((e) => typeof e.fill === 'object' || typeof e.stroke === 'object');

function vector(elements, { size = 108, viewport = 108, offset = 0 } = {}) {
  const aapt = usesGradient(elements) ? '\n    xmlns:aapt="http://schemas.android.com/aapt"' : '';
  let body = vectorPaths(elements, offset ? 8 : 4);
  if (offset) {
    // Compose resources' vectors have no viewport origin, so the 72-wide window is a translation.
    body = `    <group android:translateX="${-offset}" android:translateY="${-offset}">\n${body}\n    </group>`;
  }
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"${aapt}
    android:width="${size}dp"
    android:height="${size}dp"
    android:viewportWidth="${viewport}"
    android:viewportHeight="${viewport}">
${body}
</vector>
`;
}

function adaptive(name) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/${name}_background" />
    <foreground android:drawable="@drawable/${name}_foreground" />
    <monochrome android:drawable="@drawable/${name}_monochrome" />
</adaptive-icon>
`;
}

// ---- PNG -----------------------------------------------------------------------------------

function chrome() {
  if (process.env.CHROME) return process.env.CHROME;
  const cache = join(homedir(), 'Library/Caches/ms-playwright');
  const shells = existsSync(cache) ? readdirSync(cache).filter((d) => d.startsWith('chromium_headless_shell')).sort() : [];
  for (const shell of shells.reverse()) {
    for (const arch of ['chrome-headless-shell-mac-arm64', 'chrome-headless-shell-mac-x64', 'chrome-headless-shell-linux64']) {
      const bin = join(cache, shell, arch, 'chrome-headless-shell');
      if (existsSync(bin)) return bin;
    }
  }
  throw new Error('No headless Chromium found; set CHROME=/path/to/chrome');
}

function screenshot(html, out, width, height, transparent) {
  const page = join(tmpdir(), `app-icon-${process.pid}.html`);
  writeFileSync(page, `<!doctype html><html><body style="margin:0;background:transparent">${html}</body></html>`);
  execFileSync(chrome(), [
    '--headless', '--hide-scrollbars', '--force-device-scale-factor=1',
    `--window-size=${width},${height}`, `--screenshot=${out}`,
    ...(transparent ? ['--default-background-color=00000000'] : []),
    `file://${page}`,
  ], { stdio: 'ignore' });
  rmSync(page);
}

// App Store Connect refuses an opaque icon that still carries an alpha channel. Chromium writes an
// opaque page as plain RGB (PNG colour type 2); check it did.
function assertOpaque(file) {
  const colourType = readFileSync(file)[25];
  if (colourType !== 2) throw new Error(`${file}: PNG colour type ${colourType}, expected RGB without alpha`);
}

// ---- outputs -------------------------------------------------------------------------------

function writeAndroid(icon) {
  const name = androidName(icon);
  const drawable = join(RES, 'drawable');
  writeFileSync(join(drawable, `${name}_background.xml`), vector(icon.background));
  writeFileSync(join(drawable, `${name}_foreground.xml`), vector(icon.foreground));
  writeFileSync(join(drawable, `${name}_monochrome.xml`), vector(icon.monochrome));
  writeFileSync(join(RES, 'mipmap-anydpi', `${name}.xml`), adaptive(name));
  if (isDefault(icon)) {
    writeFileSync(join(RES, 'mipmap-anydpi', 'ic_launcher_round.xml'), adaptive(name));
    writeFileSync(join(DEBUG_RES, 'drawable', 'ic_launcher_background.xml'), vector(icon.debugBackground));
  }
}

function writeCompose(icon) {
  writeFileSync(
    join(COMPOSE, `app_icon_${icon.id}.xml`),
    vector([...icon.background, ...icon.foreground], { size: 72, viewport: 72, offset: 18 }),
  );
}

function writeIos(icon) {
  const set = join(ASSETS, `${iosName(icon)}.appiconset`);
  rmSync(set, { recursive: true, force: true });
  mkdirSync(set, { recursive: true });
  const images = [];
  screenshot(svg([icon.background, icon.foreground]), join(set, 'icon.png'), 1024, 1024, false);
  assertOpaque(join(set, 'icon.png'));
  images.push({ filename: 'icon.png', idiom: 'universal', platform: 'ios', size: '1024x1024' });
  if (icon.dark) {
    screenshot(svg([icon.dark]), join(set, 'icon-dark.png'), 1024, 1024, true);
    images.push({ appearances: [{ appearance: 'luminosity', value: 'dark' }], filename: 'icon-dark.png', idiom: 'universal', platform: 'ios', size: '1024x1024' });
    screenshot(svg([icon.monochrome]), join(set, 'icon-tinted.png'), 1024, 1024, true);
    images.push({ appearances: [{ appearance: 'luminosity', value: 'tinted' }], filename: 'icon-tinted.png', idiom: 'universal', platform: 'ios', size: '1024x1024' });
  }
  writeFileSync(join(set, 'Contents.json'), JSON.stringify({ images, info: { author: 'xcode', version: 1 } }, null, 2) + '\n');
}

function writeDesign() {
  mkdirSync(DESIGN, { recursive: true });
  for (const icon of ICONS) writeFileSync(join(DESIGN, `${icon.id}.svg`), svg([icon.background, icon.foreground], 512) + '\n');
  // The contact sheet: each icon as iOS (squircle), Android (circle), Android themed, and the
  // default's iOS dark home screen.
  const cell = 150;
  const themed = (icon) => svg([[{ d: 'M0,0h108v108h-108z', fill: '#DCE4F7' }], icon.monochrome.map((e) => ({ ...e, fill: e.fill && '#2A3A66', stroke: e.stroke && '#2A3A66' }))], cell);
  const rows = ICONS.map((icon) => `
    <div style="display:flex;gap:28px;align-items:center;margin:18px 28px">
      <div style="width:120px;font:600 20px -apple-system,Helvetica;color:#E8ECF4">${icon.id}</div>
      <div style="width:${cell}px;height:${cell}px;border-radius:34px;overflow:hidden">${svg([icon.background, icon.foreground], cell)}</div>
      <div style="width:${cell}px;height:${cell}px;border-radius:50%;overflow:hidden">${svg([icon.background, icon.foreground], cell)}</div>
      <div style="width:${cell}px;height:${cell}px;border-radius:50%;overflow:hidden">${themed(icon)}</div>
      ${icon.dark ? `<div style="width:${cell}px;height:${cell}px;border-radius:34px;overflow:hidden;background:#000">${svg([icon.dark], cell)}</div>` : ''}
    </div>`).join('');
  const height = ICONS.length * (cell + 36) + 40;
  screenshot(`<div style="background:#20232B;width:860px;height:${height}px;padding-top:20px">${rows}</div>`, join(DESIGN, 'contact-sheet.png'), 860, height, false);
}

const only = process.argv.includes('--design-only');
writeDesign();
if (!only) {
  for (const dir of [join(RES, 'drawable'), join(RES, 'mipmap-anydpi'), join(DEBUG_RES, 'drawable'), COMPOSE]) {
    mkdirSync(dir, { recursive: true });
  }
  for (const icon of ICONS) {
    writeAndroid(icon);
    writeCompose(icon);
    writeIos(icon);
  }
}
console.log(`Wrote ${ICONS.length} icons${only ? ' (design only)' : ''}.`);
